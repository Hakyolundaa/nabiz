const { contextBridge, ipcRenderer, webUtils } = require('electron');
contextBridge.exposeInMainWorld('ada', {
  clickable: v => ipcRenderer.send('clickable', !!v),
  dragStart: () => ipcRenderer.send('drag-start'),
  dragEnd: () => ipcRenderer.send('drag-end'),
  version: () => ipcRenderer.invoke('version'),
  pickUpdate: () => ipcRenderer.invoke('pick-update'),
  installUpdateFile: file => ipcRenderer.invoke('install-update', webUtils.getPathForFile(file)),
  checkOnline: () => ipcRenderer.invoke('check-online'),
  getDesk: () => ipcRenderer.invoke('get-desk'),
  setDesk: (k, v) => ipcRenderer.invoke('set-desk', k, v),
  backupInfo: () => ipcRenderer.invoke('backup-info'),
  backupToggle: on => ipcRenderer.invoke('backup-toggle', on),
  exportLibrary: () => ipcRenderer.invoke('export-library'),
  restoreLibrary: fromDropbox => ipcRenderer.invoke('restore-library', fromDropbox),
  mini: on => ipcRenderer.invoke('mini', on),
  getResume: () => ipcRenderer.invoke('get-resume'),
  islandMenu: () => ipcRenderer.send('island-menu'),
  onIslandReset: f => ipcRenderer.on('island-reset', () => f()),
  saveImage: (dataUrl, name) => ipcRenderer.invoke('save-image', dataUrl, name),
  shareCard: (dataUrl, title) => ipcRenderer.invoke('share-card', dataUrl, title),
  shareOpen: target => ipcRenderer.invoke('share-open', target),
  shareCardWeb: dataUrl => ipcRenderer.invoke('share-card-web', dataUrl),
  notify: n => ipcRenderer.invoke('notify', n),
  report: r => ipcRenderer.invoke('report', r),
  feedback: f => ipcRenderer.invoke('feedback', f),
  telemetry: on => ipcRenderer.invoke('telemetry', on),
  adminInfo: () => ipcRenderer.invoke('admin-info'),
  adminConfig: c => ipcRenderer.invoke('admin-config', c),
  adminData: d => ipcRenderer.invoke('admin-data', d),
  adminDelete: id => ipcRenderer.invoke('admin-delete', id),
  openUrl: u => ipcRenderer.invoke('open-url', u),
  islandFocusSync: () => ipcRenderer.send('island-focus-sync'),
  focused: () => document.hasFocus(),
  remote: (on, renew) => ipcRenderer.invoke('remote', on, renew),
});
